import React from "react";
import { afterEach, expect, it, vi } from "vitest";
import { cleanup, render, screen, waitFor, within } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import Index from "./Index";

const { toast } = vi.hoisted(() => ({ toast: vi.fn() }));
vi.mock("@/hooks/use-toast", () => ({ useToast: () => ({ toast }) }));
afterEach(() => { cleanup(); vi.clearAllMocks(); });

it("runs the local registration, member and admin flows without a backend", async () => {
  const fetchSpy = vi.spyOn(globalThis, "fetch");
  const user = userEvent.setup();
  render(<Index />);
  await user.click(screen.getByRole("tab", { name: "Register" }));
  await user.type(screen.getByLabelText("Full Name"), "Demo Member");
  await user.type(screen.getByLabelText("Email"), "demo@example.com");
  await user.click(screen.getByRole("button", { name: "Join Community" }));
  expect(await screen.findByText("Welcome, Demo Member!")).toBeTruthy();
  await user.click(screen.getByRole("button", { name: "Profile" }));
  expect(screen.getByText("demo@example.com")).toBeTruthy();
  expect(screen.getAllByText("Not provided").length).toBeGreaterThan(0);
  await user.click(screen.getByRole("button", { name: "Back to Home" }));
  await user.click(screen.getByRole("tab", { name: "Marriage Gold" }));
  expect(screen.getByText(`₹${(125000).toLocaleString()}`)).toBeTruthy();
  await user.click(screen.getByRole("button", { name: "Logout" }));
  await user.type(screen.getByLabelText("Email"), "admin@gmail.com");
  await user.type(screen.getByLabelText("Password"), "wrong");
  await user.click(screen.getByRole("button", { name: "Sign In" }));
  expect(toast).toHaveBeenCalledWith(expect.objectContaining({ title: "Login failed" }));
  await user.clear(screen.getByLabelText("Password"));
  await user.type(screen.getByLabelText("Password"), "admin@123");
  await user.click(screen.getByRole("button", { name: "Sign In" }));
  await screen.findByRole("heading", { name: "Admin Dashboard" });
  const amount = screen.getByLabelText("Current Amount (₹)");
  await waitFor(() => expect((amount as HTMLInputElement).value).toBe("25500"));
  await user.clear(amount);
  await user.click(screen.getByRole("button", { name: "Update Ganesh Chanda Amount" }));
  expect(toast).toHaveBeenCalledWith(expect.objectContaining({ title: "Invalid amount" }));
  await user.type(amount, "0");
  await user.click(screen.getByRole("button", { name: "Update Ganesh Chanda Amount" }));
  await waitFor(() => expect(toast).toHaveBeenCalledWith(expect.objectContaining({ title: "Ganesh Chanda Updated" })));
  await user.upload(screen.getByLabelText("Select File"), new File(["photo"], "event.png", { type: "image/png" }));
  await user.click(screen.getByRole("button", { name: "Add File to Demo" }));
  await waitFor(() => expect(toast).toHaveBeenCalledWith(expect.objectContaining({ title: "Added to demo gallery" })));
  const memberRow = screen.getByText("demo@example.com").closest(".border") as HTMLElement;
  await user.click(within(memberRow).getByRole("button", { name: "Remove" }));
  await waitFor(() => expect(screen.queryByText("demo@example.com")).toBeNull());
  await user.click(screen.getByRole("button", { name: "Logout" }));
  await user.type(screen.getByLabelText("Email"), "priya.sharma@gmail.com");
  await user.type(screen.getByLabelText("Password"), "anything");
  await user.click(screen.getByRole("button", { name: "Sign In" }));
  await screen.findByText("Welcome, Priya Sharma!");
  expect(screen.getByText("₹0")).toBeTruthy();
  await user.click(screen.getByRole("tab", { name: "Photos" }));
  expect(await screen.findByText("event.png")).toBeTruthy();
  expect(fetchSpy).not.toHaveBeenCalled();
  fetchSpy.mockRestore();
});
