import React from "react";
import { afterEach, expect, it, vi } from "vitest";
import { cleanup, render, screen, waitFor } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import AdminDashboard from "./AdminDashboard";
import { deleteUser, getFinancialData, getUsers, updateFinancialData, uploadMediaFile } from "@/services/database";
vi.mock("@/services/database", () => ({ deleteUser: vi.fn(), getFinancialData: vi.fn(), getUsers: vi.fn(), updateFinancialData: vi.fn(), uploadMediaFile: vi.fn() }));
const { toast } = vi.hoisted(() => ({ toast: vi.fn() }));
vi.mock("@/hooks/use-toast", () => ({ useToast: () => ({ toast }) }));
afterEach(() => { cleanup(); vi.resetAllMocks(); });
it("reports failed admin actions without claiming success or removing members", async () => {
  const admin = { id: "a", name: "Admin", email: "admin@gmail.com", role: "admin" as const, join_date: "2024-01-01" };
  vi.mocked(getUsers).mockResolvedValue([{ ...admin, id: "m", name: "Member", role: "member" }]);
  vi.mocked(getFinancialData).mockResolvedValue([{ id: "g", type: "ganesh_chanda", current_amount: 5 }, { id: "m", type: "marriage_gold", total_fund: 7 }]);
  vi.mocked(updateFinancialData).mockRejectedValue(new Error("failed"));
  vi.mocked(deleteUser).mockRejectedValue(new Error("failed"));
  vi.mocked(uploadMediaFile).mockRejectedValue(new Error("failed"));
  const error = vi.spyOn(console, "error").mockImplementation(() => {});
  const user = userEvent.setup();
  render(<AdminDashboard currentUser={admin} onLogout={() => {}} />);
  await screen.findByText("Member");
  const amount = screen.getByLabelText("Total Fund (₹)");
  await user.clear(amount); await user.type(amount, "-1");
  await user.click(screen.getByRole("button", { name: "Update Marriage Gold Fund" }));
  expect(updateFinancialData).not.toHaveBeenCalled();
  await user.clear(amount); await user.type(amount, "0");
  await user.click(screen.getByRole("button", { name: "Update Marriage Gold Fund" }));
  await waitFor(() => expect(toast).toHaveBeenCalledWith(expect.objectContaining({ description: "Failed to update Marriage Gold Fund" })));
  expect(screen.getByText("₹7")).toBeTruthy();
  await user.click(screen.getByRole("button", { name: "Remove" }));
  await waitFor(() => expect(toast).toHaveBeenCalledWith(expect.objectContaining({ description: "Failed to remove user" })));
  expect(screen.getByText("Member")).toBeTruthy();
  await user.upload(screen.getByLabelText("Select File"), new File(["v"], "video.mp4", { type: "video/mp4" }));
  await user.click(screen.getByRole("button", { name: "Add File to Demo" }));
  await waitFor(() => expect(toast).toHaveBeenCalledWith(expect.objectContaining({ title: "Upload failed" })));
  error.mockRestore();
});
